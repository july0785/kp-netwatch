from pathlib import Path

from .snapshot import parse_time

STATUS_START = "<!-- status:start -->"
STATUS_END = "<!-- status:end -->"
CHANGES_HEADER = "# Changes\n\nNewest run first. Generated by `python -m kpnetwatch run`.\n\n"

LABELS = {
    "asn_added": "ASN added",
    "asn_removed": "ASN removed",
    "allocation_added": "address block added",
    "allocation_removed": "address block removed",
    "asn_holder_changed": "ASN holder changed",
    "asn_announced_changed": "ASN announcement state changed",
    "upstream_added": "upstream added",
    "upstream_removed": "upstream removed",
    "prefix_new": "prefix announced",
    "prefix_withdrawn": "prefix withdrawn",
    "prefix_origin_changed": "prefix origin changed",
    "visibility_drop": "visibility dropped",
    "visibility_rise": "visibility rose",
    "cert_new": "new certificate",
    "cert_removed": "certificate gone from crt.sh",
    "cert_expired": "certificate expired",
    "dns_domain_added": "domain added",
    "dns_status_changed": "DNS status changed",
    "dns_record_changed": "DNS record changed",
    "source_error": "source error",
}


class MarkersMissing(ValueError):
    pass


def stamp(text):
    return parse_time(text).strftime("%Y-%m-%d %H:%M UTC")


def change_line(item):
    line = f"- [{item['section']}] {LABELS[item['kind']]}: {item['subject']}"
    if item["detail"]:
        line += f" ({item['detail']})"
    return line


def summary_line(summary):
    return (
        f"{summary['asns']} ASN, {summary['prefixes_announced']} prefixes announced, "
        f"{summary['certs']} certificates ({summary['certs_unexpired']} unexpired), "
        f"{summary['domains_resolving']}/{summary['domains']} names resolving."
    )


def entry(current, previous, changes):
    lines = [f"## {stamp(current['generated_at'])}", ""]
    if previous is None:
        lines += ["First snapshot. " + summary_line(current["summary"])]
    elif not changes:
        lines += [f"No changes since {stamp(previous['generated_at'])}."]
    else:
        lines += [f"Compared with {stamp(previous['generated_at'])}.", ""]
        lines += [change_line(item) for item in changes]
    errors = [name for name, status in current["summary"]["sources"].items() if status != "ok"]
    if previous is None and errors:
        lines += ["", "Sources with errors: " + ", ".join(errors) + "."]
    return "\n".join(lines) + "\n"


def prepend_changes(path, text):
    path = Path(path)
    existing = path.read_text(encoding="utf-8") if path.exists() else CHANGES_HEADER
    marker = existing.find("\n## ")
    if marker == -1:
        merged = existing.rstrip("\n") + "\n\n" + text
    else:
        head = existing[: marker + 1]
        merged = head + text + "\n" + existing[marker + 1 :]
    path.write_text(merged, encoding="utf-8", newline="\n")


def status_table(snap):
    summary = snap["summary"]
    sources = ", ".join(f"{name} {status}" for name, status in summary["sources"].items())
    rows = [
        ("last run", stamp(snap["generated_at"])),
        ("ASNs", summary["asns"]),
        ("prefixes announced", summary["prefixes_announced"]),
        ("certificates in CT", f"{summary['certs']} ({summary['certs_unexpired']} unexpired)"),
        ("names tracked", summary["domains"]),
        ("names resolving", summary["domains_resolving"]),
        ("source status", sources),
    ]
    lines = ["| item | value |", "| --- | --- |"]
    lines += [f"| {label} | {value} |" for label, value in rows]
    return "\n".join(lines)


def update_readme(path, snap):
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    start = text.find(STATUS_START)
    end = text.find(STATUS_END)
    if start == -1 or end == -1 or end < start:
        raise MarkersMissing(f"{path.name} has no status markers")
    updated = text[: start + len(STATUS_START)] + "\n" + status_table(snap) + "\n" + text[end:]
    path.write_text(updated, encoding="utf-8", newline="\n")


def report(snap):
    summary = snap["summary"]
    lines = [f"snapshot {stamp(snap['generated_at'])}", summary_line(summary)]
    lines.append("sources: " + ", ".join(f"{name} {status}" for name, status in summary["sources"].items()))
    discovery = snap["bgp"]["discovery"]
    origin = "fallback seed" if discovery["fallback"] else discovery["source"]
    lines.append(f"ASNs ({origin}): " + ", ".join(f"AS{asn}" for asn in discovery["asn"]))
    for asn, record in sorted(snap["bgp"]["asns"].items()):
        lines.append(f"  AS{asn} {record.get('holder')}")
    for prefix, record in snap["bgp"]["prefixes"].items():
        seen = f"{record['visibility']['seeing']}/{record['visibility']['total']} peers" if record["status"] == "ok" else record["status"]
        lines.append(f"  {prefix} {seen}")
    for name, record in snap["dns"]["domains"].items():
        addresses = ", ".join(record["records"].get("A", []) + record["records"].get("AAAA", [])) or "-"
        lines.append(f"  {name} {record['status']} {addresses}")
    return "\n".join(lines)
